type UseMinecraftHintsResult = {
  start: () => void
  stop: () => void
}

export const useMinecraftHints = (): UseMinecraftHintsResult => {
  const intervalRef = useRef<NodeJS.Timeout | null>(null)
  const hasFirstLaunch = useHasFirstLaunch()
  console.log('hasFirstLaunch', hasFirstLaunch)

  const getRandomHint = useCallback(() => {
    const index = Math.floor(Math.random() * HINTS.length)
    return HINTS[index]
  }, [])

  const start = useCallback(() => {
    if (intervalRef.current) return
    setHintText(hasFirstLaunch ? getRandomHint() : HINTS[0])

    intervalRef.current = setInterval(() => {
      setHintText(getRandomHint())
    }, 7000)
  }, [getRandomHint, hasFirstLaunch])

  const stop = useCallback(() => {
    if (intervalRef.current) {
      clearInterval(intervalRef.current)
      intervalRef.current = null
    }
  }, [])

  useEffect(() => {
    return () => stop()
  }, [stop])

  return { start, stop }
}
